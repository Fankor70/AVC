/**
 * Phonetics — фонетические утилиты для сопоставления произнесённых имён
 * озвучек с названиями на сайте (Task 8-b, Voice Provider Resolver).
 *
 * Проблема: Whisper распознаёт русское ПРОИЗНОШЕНИЕ («ани либрию»),
 * а на сайте озвучка хранится латиницей («AniLibria»). Нужен мост:
 *   1) stripCaseEndings — срезание русских падежных окончаний;
 *   2) phoneticKey — собственная транслитерация кириллицы в латиницу,
 *      чтобы «анилибрия» и «AniLibria» давали сопоставимые ключи.
 *
 * Файл БЕЗ внутренних зависимостей: его импортируют и fuzzy.ts,
 * и provider-resolver.ts (исключает циклический импорт).
 */

// --- Транслитерация ---------------------------------------------------------

/** Кириллица -> латиница (практичная схема, без диакритики) */
const RU_TO_LAT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p',
  р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch',
  ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

/**
 * Фонетический ключ строки: русский -> латиница (собственная транслитерация),
 * lowercase, только a-z, схлопнутые двойные буквы, пробелы/пунктуация убраны.
 *
 *   «анилибрия»  -> 'anilibriya'
 *   «AniLibria»  -> 'anilibria'
 *   «ани либрия» -> 'anilibriya'
 *   «Анимэ Вост» -> 'animevost'
 */
export function phoneticKey(s: string): string {
  const lower = s.toLowerCase().replace(/ё/g, 'е')
  let out = ''
  for (const ch of lower) {
    out += RU_TO_LAT[ch] ?? ch
  }
  // оставляем только латиницу, схлопываем повторяющиеся буквы
  return out
    .replace(/[^a-z]/g, '')
    .replace(/(.)\1+/g, '$1')
}

// --- Падежные окончания -----------------------------------------------------

/**
 * Русские падежные окончания имён собственных (проверяются от длинных к коротким).
 * Срезаем ровно ОДИН завершающий символ за проход и повторяем, пока слово
 * кончается на какое-то окончание — так все формы («анилибрия/анилибрию/анилибрии»)
 * сходятся к одному стему, что и требуется для сопоставления.
 */
const CASE_ENDINGS = [
  'ему', 'ому', 'ыю', 'ою', 'ею',
  'ия', 'ию', 'ии', 'ой', 'ый', 'ий', 'ей', 'ая', 'яя',
  'ом', 'ем', 'ам', 'ях', 'ах',
  'у', 'ю', 'я', 'ы', 'и', 'е', 'а', 'й',
] as const

/** Слово кириллическое (для латиницы падежи не применяем)? */
function isCyrillicWord(w: string): boolean {
  return /^[а-яе]+$/i.test(w)
}

function stripOnePass(w: string): string {
  for (const end of CASE_ENDINGS) {
    if (w.length > end.length && w.endsWith(end)) {
      return w.slice(0, -1) // срезаем последний символ окончания
    }
  }
  return w
}

/**
 * Урезание русских падежных окончаний для имён собственных.
 * Работает ПОСЛОВНО: слово обрабатывается, только если оно кириллическое
 * и содержит >= 5 букв (короткие слова не уродуем: «джем», «шиза», «аниме»
 * остаются как есть после первого прохода по длине).
 *
 *   «анилибрию»            -> «анилибр»
 *   «анилибрия»            -> «анилибр»  (все падежи сходятся к одному стему)
 *   «дрим каста»           -> «дрим каст»
 *   «AniLibria» (латиница) -> «AniLibria» (без изменений)
 */
export function stripCaseEndings(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => {
      if (!isCyrillicWord(w)) return w
      let cur = w
      while (cur.length >= 5) {
        const next = stripOnePass(cur)
        if (next === cur) break
        cur = next
      }
      return cur
    })
    .join(' ')
    .trim()
}
